/* ============================================================
   DYNX Labs — Insight article renderer
   File: assets/js/insight-render.js
   Shared by the browser (insights/insight-post.html) and by
   generate-manifest.js, which pre-renders every article page so
   its content is in the HTML that search engines read.
   ============================================================ */

(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.InsightRender = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  const CATEGORIES = {
    "automatizacion":          { color: "#7a3010", en: "Automation",             es: "Automatización" },
    "inteligencia-artificial": { color: "#233444", en: "Artificial Intelligence", es: "Inteligencia Artificial" },
    "casos-reales":            { color: "#0d3320", en: "Real Cases",              es: "Casos Reales" },
    "workflows":               { color: "#2a1040", en: "Workflows",               es: "Workflows" }
  };


  const SITE = 'https://dynxlabs.com';

  function getCategoryLabel(catKey, lang) {
    const cat = CATEGORIES[catKey];
    if (!cat) return catKey;
    return cat[lang] || cat.en;
  }

  function formatDate(dateStr, lang) {
    const d = new Date(dateStr + 'T00:00:00');
    return d.toLocaleDateString(lang === 'es' ? 'es-CL' : 'en-US', { year: 'numeric', month: 'long', day: 'numeric' });
  }

  // Public URL of an article; Spanish adds ?lang=es (English is the default).
  function articleUrl(slug, lang) {
    return `${SITE}/insights/${slug}/` + (lang === 'es' ? '?lang=es' : '');
  }

  // Share image generated by scripts/og-images.js.
  function imageUrl(slug) {
    return `${SITE}/assets/images/og/insights/${slug}.png`;
  }

  // article: manifest entry with en/es bodies merged in.
  function render(article, manifest, lang) {
    const data     = article[lang] || article.en;
    const catLabel = getCategoryLabel(article.category, lang);
    const readTime = article.readTime[lang] || article.readTime.en;
    const dateStr  = formatDate(article.date, lang);
    const url      = articleUrl(article.slug, lang);

    const jsonLd = {
      "@context": "https://schema.org",
      "@type": "BlogPosting",
      "headline": data.title,
      "description": data.summary,
      "datePublished": article.date,
      "author": { "@type": "Person", "name": "Arois Monsalve", "jobTitle": "CEO & Founder", "url": "https://www.linkedin.com/in/aroismonsalve/", "worksFor": { "@type": "Organization", "name": "DYNX Labs", "url": "https://dynxlabs.com" } },
      "publisher": { "@type": "Organization", "name": "DYNX Labs", "url": "https://dynxlabs.com", "logo": { "@type": "ImageObject", "url": "https://dynxlabs.com/assets/images/og-image.png" } },
      "mainEntityOfPage": { "@type": "WebPage", "@id": url },
      "inLanguage": lang === 'es' ? 'es' : 'en',
      "image": imageUrl(article.slug)
    };

    const breadcrumb = {
      "@context": "https://schema.org",
      "@type": "BreadcrumbList",
      "itemListElement": [
        { "@type": "ListItem", "position": 1, "name": "DYNX Labs", "item": SITE + "/" },
        { "@type": "ListItem", "position": 2, "name": "Insights", "item": SITE + "/insights" + (lang === 'es' ? '?lang=es' : '') },
        { "@type": "ListItem", "position": 3, "name": data.title, "item": url }
      ]
    };

    const related = (manifest.articles || [])
      .filter(a => a.slug !== article.slug && a.category === article.category)
      .slice(0, 3);

    const relatedHtml = related.length > 0 ? `
      <hr class="post-divider" />
      <section class="post-related" aria-label="${lang === 'es' ? 'Artículos relacionados' : 'Related articles'}">
        <div class="post-related__title">${lang === 'es' ? 'Artículos relacionados' : 'Related articles'}</div>
        <div class="post-related__grid">
          ${related.map(r => {
            const rd = r[lang] || r.en;
            return `
              <a href="/insights/${r.slug}/" class="post-related__card">
                <div class="post-related__card-bar"></div>
                <div class="post-related__card-title">${rd.title}</div>
                <div class="post-related__card-meta">${r.readTime[lang] || r.readTime.en}</div>
              </a>`;
          }).join('')}
        </div>
      </section>` : '';

    const bodyHtml = data.body
      ? `<div class="post-body">${data.body}</div>`
      : `<div class="post-placeholder">
          <div class="post-placeholder__icon">✍️</div>
          <div class="post-placeholder__title">${lang === 'es' ? 'Contenido próximamente' : 'Full article coming soon'}</div>
          <p class="post-placeholder__text">
            ${lang === 'es'
              ? 'Estamos preparando el contenido completo de este artículo. Mientras tanto, contáctanos si tienes preguntas.'
              : "We're preparing the full content for this article. In the meantime, reach out if you have questions."}
          </p>
          <a href="https://wa.me/56984657801" target="_blank" rel="noopener noreferrer" class="post-placeholder__cta">
            <svg width="14" height="14" viewBox="0 0 24 24" fill="currentColor"><path d="M17.472 14.382c-.297-.149-1.758-.867-2.03-.967-.273-.099-.471-.148-.67.15-.197.297-.767.966-.94 1.164-.173.199-.347.223-.644.075-.297-.15-1.255-.463-2.39-1.475-.883-.788-1.48-1.761-1.653-2.059-.173-.297-.018-.458.13-.606.134-.133.298-.347.446-.52.149-.174.198-.298.298-.497.099-.198.05-.371-.025-.52-.075-.149-.669-1.612-.916-2.207-.242-.579-.487-.5-.669-.51-.173-.008-.371-.01-.57-.01-.198 0-.52.074-.792.372-.272.297-1.04 1.016-1.04 2.479 0 1.462 1.065 2.875 1.213 3.074.149.198 2.096 3.2 5.077 4.487.709.306 1.262.489 1.694.625.712.227 1.36.195 1.871.118.571-.085 1.758-.719 2.006-1.413.248-.694.248-1.289.173-1.413-.074-.124-.272-.198-.57-.347m-5.421 7.403h-.004a9.87 9.87 0 01-5.031-1.378l-.361-.214-3.741.982.998-3.648-.235-.374a9.86 9.86 0 01-1.51-5.26c.001-5.45 4.436-9.884 9.888-9.884 2.64 0 5.122 1.03 6.988 2.898a9.825 9.825 0 012.893 6.994c-.003 5.45-4.437 9.884-9.885 9.884m8.413-18.297A11.815 11.815 0 0012.05 0C5.495 0 .16 5.335.157 11.892c0 2.096.547 4.142 1.588 5.945L.057 24l6.305-1.654a11.882 11.882 0 005.683 1.448h.005c6.554 0 11.89-5.335 11.893-11.893a11.821 11.821 0 00-3.48-8.413Z"/></svg>
            ${lang === 'es' ? 'Contáctanos' : 'Contact us'}
          </a>
        </div>`;


    const html = `
      <div class="post-hero">
        <a href="/insights" class="post-hero__back">
          <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="m15 18-6-6 6-6"/></svg>
          ${lang === 'es' ? 'Volver a Insights' : 'Back to Insights'}
        </a>
        <div class="post-hero__badge">
          ${catLabel}
        </div>
        <h1 class="post-hero__title">${data.title}</h1>
        <p class="post-hero__summary">${data.summary}</p>
        <div class="post-hero__meta">
          <span>${dateStr}</span>
          <span class="post-hero__meta-dot">·</span>
          <span>${readTime}</span>
        </div>
      </div>

      <div class="post-color-bar"></div>

      <div class="post-content">
        ${bodyHtml}

        ${data.body ? `<div class="post-author">
          <div class="post-author__header">
            <svg class="post-author__icon" viewBox="0 0 2.38 3.28" xmlns="http://www.w3.org/2000/svg"><path fill="#B3B3B3" fill-rule="nonzero" d="M0.54 2.64l1.31 -0.39 0 -0.61 0 0 0 -0.61 -1.31 -0.4 0 2.01zm0.32 0.47l-0.5 0.15c-0.03,0.01 -0.06,0.02 -0.09,0.02 -0.15,0 -0.27,-0.12 -0.27,-0.27l0 -2.74c0,-0.03 0,-0.05 0.01,-0.08 0.04,-0.14 0.19,-0.22 0.34,-0.18l1.84 0.56 0 0c0.11,0.03 0.19,0.14 0.19,0.26l0 0.81 0 0 0 0.81c0,0.11 -0.07,0.22 -0.19,0.26l-1.33 0.4z"/></svg>
            <div>
              <p class="post-author__name">Arois Monsalve</p>
              <p class="post-author__role">CEO & Founder, DYNX Labs</p>
            </div>
          </div>
          <p class="post-author__bio">${lang === 'es'
            ? 'Apasionado por la automatización inteligente y la IA aplicada a operaciones de negocio. Ayudo a empresas a eliminar trabajo manual y escalar sus procesos con tecnología.'
            : 'Passionate about intelligent automation and AI applied to business operations. I help companies eliminate manual work and scale their processes with technology.'}</p>
          <div class="post-author__links">
            <a href="https://www.linkedin.com/in/aroismonsalve/" target="_blank" rel="noopener noreferrer" class="post-author__link">
              <svg viewBox="0 0 24 24" fill="currentColor"><path d="M20.447 20.452h-3.554v-5.569c0-1.328-.027-3.037-1.852-3.037-1.853 0-2.136 1.445-2.136 2.939v5.667H9.351V9h3.414v1.561h.046c.477-.9 1.637-1.85 3.37-1.85 3.601 0 4.267 2.37 4.267 5.455v6.286zM5.337 7.433a2.062 2.062 0 01-2.063-2.065 2.064 2.064 0 112.063 2.065zm1.782 13.019H3.555V9h3.564v11.452zM22.225 0H1.771C.792 0 0 .774 0 1.729v20.542C0 23.227.792 24 1.771 24h20.451C23.2 24 24 23.227 24 22.271V1.729C24 .774 23.2 0 22.222 0h.003z"/></svg>
              ${lang === 'es' ? 'Seguir en LinkedIn' : 'Follow on LinkedIn'}
            </a>
            <a href="https://dynxlabs.com" target="_blank" rel="noopener noreferrer" class="post-author__link">
              <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><circle cx="12" cy="12" r="10"/><line x1="2" y1="12" x2="22" y2="12"/><path d="M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"/></svg>
              dynxlabs.com
            </a>
          </div>
        </div>` : ''}
      </div>

      ${relatedHtml}`;

    return { title: data.title, summary: data.summary, url, html, jsonLd, breadcrumb };
  }

  return { CATEGORIES, getCategoryLabel, formatDate, articleUrl, imageUrl, render };
});
